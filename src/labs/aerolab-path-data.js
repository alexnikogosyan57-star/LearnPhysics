export function ensureAeroLearningState(data) {
  if (!data.aerolabLearning) {
    data.aerolabLearning = {
      activeMode: 'path', // 'path' | 'sandbox'
      currentLessonId: null, // null or '1.1'...'1.5'
      activeStep: 0,
      userPrediction: null,
      challengeSelected: null,
      challengeSubmitted: false,
      showHint: false,
      xp: 0,
      streak: 1,
      completedLessons: [],
      lessonScores: {},
      diyProgress: {
        materialsChecked: [],
        stepsCompleted: [],
      },
    };
  }
  const s = data.aerolabLearning;
  s.completedLessons ||= [];
  s.lessonScores ||= {};
  s.diyProgress ||= { materialsChecked: [], stepsCompleted: [] };
  s.diyProgress.materialsChecked ||= [];
  s.diyProgress.stepsCompleted ||= [];
  s.xp ||= 0;
  s.streak = Math.max(1, s.streak || 1);
  return s;
}

export function canOpenAeroLesson(state, lessonId) {
  if (lessonId === '1.1') return true;
  const num = parseFloat(lessonId);
  const prevLessonId = (num - 0.1).toFixed(1);
  return state.completedLessons.includes(prevLessonId);
}

export function recordAeroLessonCompletion(data, lessonId, xpGained = 50) {
  const s = ensureAeroLearningState(data);
  if (!s.completedLessons.includes(lessonId)) {
    s.completedLessons.push(lessonId);
    s.xp += xpGained;
    s.lessonScores[lessonId] = {
      completedAt: new Date().toISOString(),
      xp: xpGained,
    };
  }
}

export function toggleDiyStep(data, stepIndex) {
  const s = ensureAeroLearningState(data);
  const idx = s.diyProgress.stepsCompleted.indexOf(stepIndex);
  if (idx >= 0) {
    s.diyProgress.stepsCompleted.splice(idx, 1);
  } else {
    s.diyProgress.stepsCompleted.push(stepIndex);
  }
}

export function toggleDiyMaterial(data, materialId) {
  const s = ensureAeroLearningState(data);
  const idx = s.diyProgress.materialsChecked.indexOf(materialId);
  if (idx >= 0) {
    s.diyProgress.materialsChecked.splice(idx, 1);
  } else {
    s.diyProgress.materialsChecked.push(materialId);
  }
}
